CREATE SEQUENCE IF NOT EXISTS revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE course_category
(
    category_id BIGINT NOT NULL,
    course_id   BIGINT NOT NULL,
    CONSTRAINT pk_course_category PRIMARY KEY (category_id, course_id)
);

CREATE TABLE courses
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    title           VARCHAR(100)                            NOT NULL,
    code            VARCHAR(20)                             NOT NULL,
    description     TEXT,
    credit          INTEGER                                 NOT NULL,
    fee             DECIMAL(10, 2)                          NOT NULL,
    capacity        INTEGER                                 NOT NULL,
    available_seats INTEGER                                 NOT NULL,
    teacher_id      BIGINT,
    CONSTRAINT pk_courses PRIMARY KEY (id)
);

CREATE TABLE departments
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    name        VARCHAR(100)                            NOT NULL,
    code        VARCHAR(20),
    description TEXT,
    CONSTRAINT pk_departments PRIMARY KEY (id)
);

CREATE TABLE enrollments
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    student_id      BIGINT                                  NOT NULL,
    course_id       BIGINT                                  NOT NULL,
    enrollment_date TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    original_fee    DECIMAL(10, 2)                          NOT NULL,
    discount_amount DECIMAL(10, 2)                          NOT NULL,
    final_fee       DECIMAL(10, 2)                          NOT NULL,
    status          VARCHAR(20)                             NOT NULL,
    note            TEXT,
    CONSTRAINT pk_enrollments PRIMARY KEY (id)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE students
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    first_name    VARCHAR(50)                             NOT NULL,
    last_name     VARCHAR(50)                             NOT NULL,
    email         VARCHAR(100),
    phone_number  VARCHAR(20),
    date_of_birth date,
    gender        VARCHAR(10),
    is_active     BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_students PRIMARY KEY (id)
);

CREATE TABLE subject_category
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    name        VARCHAR(50)                             NOT NULL,
    description TEXT,
    CONSTRAINT pk_subject_category PRIMARY KEY (id)
);

CREATE TABLE teacher_profiles
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at          TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    qualification       VARCHAR(100),
    years_of_experience INTEGER,
    emergency_phone     VARCHAR(20),
    bio                 TEXT,
    CONSTRAINT pk_teacher_profiles PRIMARY KEY (id)
);

CREATE TABLE teachers
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    first_name    VARCHAR(50)                             NOT NULL,
    last_name     VARCHAR(50)                             NOT NULL,
    email         VARCHAR(100)                            NOT NULL,
    phone_number  VARCHAR(20),
    gender        VARCHAR(10),
    department_id BIGINT,
    profile_id    BIGINT,
    CONSTRAINT pk_teachers PRIMARY KEY (id)
);

CREATE TABLE user_roles
(
    user_id BIGINT NOT NULL,
    role    VARCHAR(255)
);

CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    username   VARCHAR(50)                             NOT NULL,
    email      VARCHAR(100)                            NOT NULL,
    password   VARCHAR(255)                            NOT NULL,
    full_name  VARCHAR(50),
    is_active  BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

